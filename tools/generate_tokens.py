#!/usr/bin/env python3
"""Swift types are `nonisolated` because the app target uses MainActor default isolation;
widgets and background code must be able to read tokens too.

Generate native design tokens from design-tokens/tokens.json.

Run from the repo root:  python3 tools/generate_tokens.py
Outputs (do not edit by hand):
  ios/Shared/Tokens.generated.swift
  android/app/src/main/java/app/quietreading/designsystem/Tokens.generated.kt
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "design-tokens/tokens.json").read_text())
th = T["themes"]; modes = th["modes"]; names = th["modeNames"]
HEADER = "// GENERATED by tools/generate_tokens.py from design-tokens/tokens.json. Do not edit.\n"

def hx(h): return h.lstrip("#").upper()

# ---------- Swift ----------
sw = [HEADER, "import SwiftUI\n",
      "/// One palette per theme mode. Night = dark, High contrast = accessibility. Both are free.",
      "nonisolated public enum ThemeID: String, CaseIterable, Codable, Sendable {"]
for m, n in zip(modes, names): sw.append(f'    case {m} // {n}')
sw += ["", "    public var displayName: String {", "        switch self {"]
for m, n in zip(modes, names): sw.append(f'        case .{m}: "{n.split(" · ")[-1]}"')
sw += ["        }", "    }", "", "    public var requiresPlus: Bool {", "        switch self {"]
for m, p in zip(modes, th["plus"]): sw.append(f'        case .{m}: {"true" if p else "false"}')
sw += ["        }", "    }", "}", "",
       "nonisolated public struct Palette: Sendable {"]
for k in th["colors"]: sw.append(f"    public let {k}: Color")
sw += ["}", "", "nonisolated public struct Radii: Sendable {"]
for k in th["radius"]: sw.append(f"    public let {k}: CGFloat")
sw += ["}", "", "nonisolated public struct HeadFont: Sendable {", "    public let family: String", "    public let weight: Font.Weight", "}", "",
       "nonisolated extension Color {", "    init(hex: UInt32) {",
       "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255, opacity: 1)",
       "    }", "}", "", "nonisolated extension ThemeID {", "    public var palette: Palette {", "        switch self {"]
for i, m in enumerate(modes):
    args = ", ".join(f"{k}: Color(hex: 0x{hx(v[i])})" for k, v in th["colors"].items())
    sw.append(f"        case .{m}: Palette({args})")
sw += ["        }", "    }", "", "    public var radii: Radii {", "        switch self {"]
for i, m in enumerate(modes):
    args = ", ".join(f"{k}: {v[i]}" for k, v in th["radius"].items())
    sw.append(f"        case .{m}: Radii({args})")
wmap = {"Regular": ".regular", "Medium": ".medium", "SemiBold": ".semibold", "Bold": ".bold"}
sw += ["        }", "    }", "", "    public var headFont: HeadFont {", "        switch self {"]
for i, m in enumerate(modes):
    sw.append(f'        case .{m}: HeadFont(family: "{th["headFont"]["family"][i]}", weight: {wmap[th["headFont"]["weight"][i]]})')
sw += ["        }", "    }", "}", ""]
def swift_enum(name, d, typ="CGFloat"):
    out = [f"nonisolated public enum {name} {{"]
    for k, v in d.items(): out.append(f"    public static let {k}: {typ} = {v}")
    out.append("}"); return out
sw += swift_enum("Space", T["space"]) + [""] + swift_enum("Size", T["size"]) + [""]
sw += ["/// Durations in seconds.", "nonisolated public enum Motion {"] + [f"    public static let {k}: Double = {v/1000}" for k, v in T["motion"].items()] + ["}", ""]
sw += swift_enum("Opacity", T["opacity"], "Double")

# Plus widget styles (Soft / Colourful / Modern), for both platforms.
ws = {k: v for k, v in T.get("widgetStyles", {}).items() if not k.startswith("_")}
if ws:
    def col(h):
        h = hx(h)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
        return f"Color(hex: 0x{h[:6]}).opacity({a:.2f})" if a < 1 else f"Color(hex: 0x{h[:6]})"
    sw += ["", "/// Plus widget styles (Figma › Widgets Final). Soft = pastel tints, Colourful = gradients, Modern = graphite.",
           "nonisolated public enum WidgetStyleID: String, CaseIterable, Codable, Sendable {"]
    sw += [f"    case {k} // {v['name']}" for k, v in ws.items()]
    sw += ["", "    public var displayName: String {", "        switch self {"]
    sw += [f'        case .{k}: "{v["name"]}"' for k, v in ws.items()]
    sw += ["        }", "    }", "", "    public var family: String {", "        switch self {"]
    sw += [f'        case .{k}: "{v["family"]}"' for k, v in ws.items()]
    sw += ["        }", "    }", "", "    public var palette: WidgetPalette {", "        switch self {"]
    for k, v in ws.items():
        bg = ", ".join(col(c) for c in v["background"])
        sw.append(f"        case .{k}: WidgetPalette(background: [{bg}], ink: {col(v['ink'])}, ink2: {col(v['ink2'])}, accent: {col(v['accent'])}, track: {col(v['track'])}, button: {col(v['button'])}, buttonInk: {col(v['buttonInk'])}, hairline: {col(v['hairline'])})")
    sw += ["        }", "    }", "}", "",
           "nonisolated public struct WidgetPalette: Sendable {",
           "    public let background: [Color]", "    public let ink: Color", "    public let ink2: Color", "    public let accent: Color",
           "    public let track: Color", "    public let button: Color", "    public let buttonInk: Color", "    public let hairline: Color", "}"]

ios = ROOT / "ios/Shared/Tokens.generated.swift"
ios.parent.mkdir(parents=True, exist_ok=True); ios.write_text("\n".join(sw) + "\n")

# ---------- Kotlin ----------
kt = [HEADER.replace("//", "//"), "package app.quietreading.designsystem\n",
      "import androidx.compose.runtime.Immutable", "import androidx.compose.ui.graphics.Color",
      "import androidx.compose.ui.text.font.FontWeight", "import androidx.compose.ui.unit.dp", "",
      "enum class ThemeId(val displayName: String, val requiresPlus: Boolean) {"]
kt += [f'    {m.upper() if False else m[0].upper()+m[1:]}("{n.split(" · ")[-1]}", {"true" if p else "false"}),' for m, n, p in zip(modes, names, th["plus"])]
kt[-1] = kt[-1].rstrip(",") + ";"
kt += ["}", "", "@Immutable", "data class QsColors("] + [f"    val {k}: Color," for k in th["colors"]] + [")", "",
       "@Immutable", "data class QsShapes("] + [f"    val {k}: androidx.compose.ui.unit.Dp," for k in th["radius"]] + [")", "",
       "@Immutable", "data class QsHeadFont(val family: String, val weight: FontWeight)", "",
       "fun ThemeId.colors(): QsColors = when (this) {"]
for i, m in enumerate(modes):
    args = ", ".join(f"{k} = Color(0xFF{hx(v[i])})" for k, v in th["colors"].items())
    kt.append(f"    ThemeId.{m[0].upper()+m[1:]} -> QsColors({args})")
kt += ["}", "", "fun ThemeId.shapes(): QsShapes = when (this) {"]
for i, m in enumerate(modes):
    args = ", ".join(f"{k} = {v[i]}.dp" for k, v in th["radius"].items())
    kt.append(f"    ThemeId.{m[0].upper()+m[1:]} -> QsShapes({args})")
kwmap = {"Regular": "FontWeight.Normal", "Medium": "FontWeight.Medium", "SemiBold": "FontWeight.SemiBold", "Bold": "FontWeight.Bold"}
kt += ["}", "", "fun ThemeId.headFont(): QsHeadFont = when (this) {"]
for i, m in enumerate(modes):
    kt.append(f'    ThemeId.{m[0].upper()+m[1:]} -> QsHeadFont("{th["headFont"]["family"][i]}", {kwmap[th["headFont"]["weight"][i]]})')
kt += ["}", "", "object QsSpace {"] + [f"    val {k} = {v}.dp" for k, v in T["space"].items()] + ["}", "",
       "object QsSize {"] + [f"    val {k} = {v}.dp" for k, v in T["size"].items()] + ["}", "",
       "/** Durations in milliseconds. */", "object QsMotion {"] + [f"    const val {k} = {v}" for k, v in T["motion"].items()] + ["}", "",
       "object QsOpacity {"] + [f"    const val {k} = {v}f" for k, v in T["opacity"].items()] + ["}"]
if ws:
    def kcol(h):
        h = hx(h)
        return f"Color(0x{h[6:8] if len(h) == 8 else 'FF'}{h[:6]})"
    kt += ["", "/** Plus widget styles (Figma › Widgets Final). Soft = pastel tints, Colourful = gradients, Modern = graphite. */",
           "enum class WidgetStyleId(val displayName: String, val family: String) {"]
    kt += [f'    {k[0].upper()+k[1:]}("{v["name"]}", "{v["family"]}"),' for k, v in ws.items()]
    kt[-1] = kt[-1].rstrip(",") + ";"
    kt += ["", "    val palette: WidgetPalette get() = when (this) {"]
    for k, v in ws.items():
        bg = ", ".join(kcol(c) for c in v["background"])
        kt.append(f"        {k[0].upper()+k[1:]} -> WidgetPalette(background = listOf({bg}), ink = {kcol(v['ink'])}, ink2 = {kcol(v['ink2'])}, accent = {kcol(v['accent'])}, track = {kcol(v['track'])}, button = {kcol(v['button'])}, buttonInk = {kcol(v['buttonInk'])}, hairline = {kcol(v['hairline'])})")
    kt += ["    }", "}", "", "@Immutable",
           "data class WidgetPalette(val background: List<Color>, val ink: Color, val ink2: Color, val accent: Color, val track: Color, val button: Color, val buttonInk: Color, val hairline: Color)"]
and_ = ROOT / "android/app/src/main/java/app/quietreading/designsystem/Tokens.generated.kt"
and_.parent.mkdir(parents=True, exist_ok=True); and_.write_text("\n".join(kt) + "\n")
print("wrote", ios.relative_to(ROOT), "and", and_.relative_to(ROOT))
