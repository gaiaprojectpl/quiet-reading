"""iOS icons (ios/QuietReading/Assets.xcassets/qs.*.imageset/*.svg) → Android VectorDrawables
(android/app/src/main/res/drawable/ic_qs_<name>.xml). Colours become black so the icons can be tinted in code.
Run: python3 tools/svg_to_vector.py"""
import glob, os, re, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ios/QuietReading/Assets.xcassets")
OUT = os.path.join(ROOT, "android/app/src/main/res/drawable")

def num(v):
    return re.sub(r"[a-z]+$", "", v)

def convert(svg_path, name):
    keep = name.startswith("logo")  # the logo keeps its own colours (no tint)
    col = lambda c: "#FF" + c[1:].upper() if keep and c.startswith("#") and len(c) == 7 else "#FF000000"
    tree = ET.parse(svg_path)
    root = tree.getroot()
    vb = root.get("viewBox", "0 0 24 24").split()
    w, h = vb[2], vb[3]
    top_fill = root.get("fill")
    paths = []
    for el in root.iter():
        if not el.tag.endswith("path"):
            continue
        d = el.get("d")
        fill = el.get("fill", top_fill if top_fill != "none" else None)
        stroke = el.get("stroke")
        attrs = [f'android:pathData="{d}"']
        if fill and fill != "none":
            attrs.append(f'android:fillColor="{col(fill)}"')
        else:
            attrs.append('android:fillColor="#00000000"')
        if el.get("fill-rule") == "evenodd":
            attrs.append('android:fillType="evenOdd"')
        if stroke and stroke != "none":
            attrs.append(f'android:strokeColor="{col(stroke)}"')
            attrs.append(f'android:strokeWidth="{num(el.get("stroke-width", "1"))}"')
            if el.get("stroke-linecap"):
                attrs.append(f'android:strokeLineCap="{el.get("stroke-linecap")}"')
            if el.get("stroke-linejoin"):
                attrs.append(f'android:strokeLineJoin="{el.get("stroke-linejoin")}"')
        paths.append("    <path " + "\n        ".join(attrs) + " />")
    size = 24
    xml = (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/svg_to_vector.py from the iOS asset (Tabler, MIT). Tint in code. -->\n'
           f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="{size}dp" android:height="{size}dp"\n'
           f'    android:viewportWidth="{w}" android:viewportHeight="{h}">\n' + "\n".join(paths) + "\n</vector>\n")
    with open(os.path.join(OUT, f"ic_qs_{name}.xml"), "w") as f:
        f.write(xml)

count = 0
for folder in sorted(glob.glob(os.path.join(SRC, "qs.*.imageset"))):
    svgs = glob.glob(os.path.join(folder, "*.svg"))
    if not svgs:
        continue
    name = os.path.basename(folder)[3:-len(".imageset")].replace("-", "_").replace(".", "_")
    convert(svgs[0], name)
    count += 1
print(f"{count} icons written to {OUT}")
